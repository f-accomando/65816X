#!/usr/bin/env python3
"""gen_c816_tables.py - generate the decode and sequence tables of the new CPU core.

Source: rtl/cpu/c816_tables.txt (format: docs/design/cpu-core.md, sections 4 and 5).

  gen_c816_tables.py               write rtl/cpu/c816_decode.v and rtl/cpu/c816_ucode.v
  gen_c816_tables.py --out DIR     write the two files in DIR
  gen_c816_tables.py --check       check the source; fail if a committed file is out of date
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPU = os.path.join(ROOT, 'rtl', 'cpu')
SOURCE = os.path.join(CPU, 'c816_tables.txt')
HEADER = "// generated by sim/gen_c816_tables.py: do not edit (source: c816_tables.txt)\n"

# field name -> (width, {name: code}); "-" is the first name unless the table says otherwise
FIELDS = {
    'bus': (3, 'IO OPF PRG DAT DRD DWR MOD'),
    'asel': (5, 'PC PCD EA EA1 DUMI S S1 VEC VEC1 DP0 DP1 DX0 DX1 LP0 LP1 LP2 SR0 SR1 '
                'SW S1W AB0 AB1 AB2 PX0 PX1 MVS MVD EAL'),
    'cap': (3, 'NONE AL AH BA DL DH IR OF'),
    'pc': (1, 'NONE INC'),
    'sop': (2, 'NONE INC DEC'),
    'wsel': (4, 'RLO RHI PCDL PCDH ALUL ALUH DL PBR AL AH PCL PCH PERL PERH PSW'),
    'last': (3, 'NO ALW W8 NTK NEC EMU NDIV'),
    'skip': (3, 'NO XNC W8 DL0 EMU'),
    'pcop': (4, 'NONE ABS LONG BRL BR RTS REL16 RTL DPTR DPTRL REWIND VECT'),
    'hold': (2, 'NONE WIDE WAI STP'),
    'op': (5, 'NOP LD ST TR ADC SBC CMP AND ORA EOR INC DEC FLG REP SEP XCE BR BRA WDM '
              'ASL LSR ROL ROR TSB TRB BIT BITI XBA PLP MVN MVP BRK'),
    'ea': (4, 'NONE ABS ABSX LONG ABSY LONGX LONGY DP DPX DPY SR'),
    'w': (3, 'M X B8 W16'),
    'src': (4, 'NONE A X Y S D P DBR PBR'),
    'dst': (4, 'NONE A X Y S D P DBR PBR'),
}
DASH = {'w': 'B8'}
SEQ_BITS = 6
STEP_FIELDS = ('bus', 'asel', 'cap', 'pc', 'sop', 'wsel', 'last', 'skip', 'pcop', 'hold')
STEP_PORTS = {'pc': 'pcinc'}
STEP_DEFAULT = {'bus': 'IO', 'last': 'ALW'}
FETCH = {'bus': 'OPF', 'asel': 'PC', 'cap': 'IR', 'pc': 'INC', 'last': 'NO'}
OP_FIELDS = ('seq', 'op', 'ea', 'w', 'src', 'dst', 'arg')


class TableError(Exception):
    pass


def code(field, text, where):
    width, names = FIELDS[field]
    names = names.split()
    if text == '-':
        text = DASH.get(field, names[0])
    if text not in names:
        raise TableError("%s: '%s' is not a value of %s" % (where, text, field))
    return names.index(text)


def parse(path):
    """Return (sequences: [(name, {t: {field: code}})], rows: [(opcode, mnemonic, {field: code})])"""
    seqs, rows, current, mode = [], [], None, None
    for number, raw in enumerate(open(path, encoding='utf-8'), 1):
        line = raw.split('#')[0].split()
        if not line:
            continue
        where = "%s:%d" % (os.path.basename(path), number)
        if line[0] == '[seq':
            current = (line[1].rstrip(']'), {})
            seqs.append(current)
            mode = 'seq'
        elif line[0] == '[ops]':
            mode = 'ops'
        elif mode == 'seq':
            if len(line) != 1 + len(STEP_FIELDS):
                raise TableError(where + ": a step line has %d fields" % (1 + len(STEP_FIELDS)))
            t = int(line[0])
            if t != len(current[1]) + 1 or t > 15:
                raise TableError(where + ": steps must be 1, 2, 3, ... up to 15")
            current[1][t] = {f: code(f, v, where) for f, v in zip(STEP_FIELDS, line[1:])}
        elif mode == 'ops':
            if len(line) != 2 + len(OP_FIELDS):
                raise TableError(where + ": a decode row has %d fields" % (2 + len(OP_FIELDS)))
            opcode = int(line[0], 16)
            if not 0 <= opcode <= 0x1FF or any(r[0] == opcode for r in rows):
                raise TableError(where + ": bad or repeated opcode")
            values = {}
            for field, text in zip(OP_FIELDS, line[2:]):
                if field == 'seq':
                    names = [s[0] for s in seqs]
                    if text not in names:
                        raise TableError(where + ": unknown sequence " + text)
                    values[field] = names.index(text)
                elif field == 'arg':
                    values[field] = int(text, 16)
                    if not 0 <= values[field] <= 15:
                        raise TableError(where + ": arg has 4 bits")
                else:
                    values[field] = code(field, text, where)
            rows.append((opcode, line[1], values))
        else:
            raise TableError(where + ": line outside a section")
    if not seqs or seqs[0][0] != 'IMP':
        raise TableError("the first sequence must be IMP")
    if len(seqs) > 1 << SEQ_BITS or len({s[0] for s in seqs}) != len(seqs):
        raise TableError("sequence names must be unique, %d at most" % (1 << SEQ_BITS))
    if 'WDMX' not in [s[0] for s in seqs]:
        raise TableError("the sequence WDMX is missing")
    for name, steps in seqs:
        if not steps or steps[len(steps)]['last'] != code('last', 'ALW', name):
            raise TableError("sequence %s: the last step must be ALW" % name)
    return seqs, rows


def literal(width, value):
    return "%d'd%d" % (width, value)


def decode_text(seqs, rows):
    names = [s[0] for s in seqs]
    ports = [('seq', SEQ_BITS)] + [(f, FIELDS[f][0]) for f in OP_FIELDS[1:-1]] + [('arg', 4)]
    out = ["module c816_decode (", "  input [8:0] ir,"]
    out += ["  output reg [%d:0] %s," % (w - 1, n) for n, w in ports]
    out += ["  output reg imp,", "  output [%d:0] seq_wdmx" % (SEQ_BITS - 1), ");",
            "  assign seq_wdmx = %s;" % literal(SEQ_BITS, names.index('WDMX')),
            "  always @* begin",
            "    " + " ".join("%s = %s;" % (n, literal(w, 0)) for n, w in ports) + " imp = 1'b0;",
            "    case (ir)"]
    for opcode, mnemonic, v in sorted(rows):
        body = " ".join("%s = %s;" % (n, literal(w, v[n])) for n, w in ports)
        out.append("      9'h%03X: begin %s imp = 1'b1; end  // %s" % (opcode, body, mnemonic))
    out += ["      default: ;", "    endcase", "  end", "endmodule", ""]
    return HEADER + "\n".join(out)


def ucode_text(seqs):
    ports = [(f, STEP_PORTS.get(f, f), FIELDS[f][0]) for f in STEP_FIELDS]
    default = {f: code(f, STEP_DEFAULT.get(f, '-'), 'default') for f in STEP_FIELDS}
    fetch = {f: code(f, FETCH.get(f, '-'), 'fetch') for f in STEP_FIELDS}

    def assign(values):
        return " ".join("%s = %s;" % (port, literal(w, values[f])) for f, port, w in ports)

    out = ["module c816_ucode (", "  input [%d:0] seq," % (SEQ_BITS - 1), "  input [3:0] t,"]
    out += ["  output reg [%d:0] %s%s" % (w - 1, port, "," if i + 1 < len(ports) else "")
            for i, (_, port, w) in enumerate(ports)]
    out += [");", "  always @* begin", "    " + assign(default),
            "    if (t == 4'd0) begin", "      " + assign(fetch), "    end else begin",
            "      case ({seq, t})"]
    for number, (name, steps) in enumerate(seqs):
        for t, values in sorted(steps.items()):
            changed = " ".join("%s = %s;" % (port, literal(w, values[f]))
                               for f, port, w in ports if values[f] != default[f])
            out.append("        %d'h%03X: begin %s end  // %s %d"
                       % (SEQ_BITS + 4, number << 4 | t, changed, name, t))
    out += ["        default: ;", "      endcase", "    end", "  end", "endmodule", ""]
    return HEADER + "\n".join(out)


def generate():
    seqs, rows = parse(SOURCE)
    return {'c816_decode.v': decode_text(seqs, rows), 'c816_ucode.v': ucode_text(seqs)}, seqs, rows


def main(argv):
    args = argv[1:]
    try:
        files, seqs, rows = generate()
    except TableError as e:
        print("ERROR: %s" % e)
        return 1
    if args == ['--check']:
        stale = []
        for name, text in files.items():
            path = os.path.join(CPU, name)
            old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
            if old != text:
                stale.append(name)
        for name in stale:
            print("ERROR: rtl/cpu/%s is out of date (run: make tables)" % name)
        print("%d sequences, %d decode rows%s" % (len(seqs), len(rows), "" if stale else ": up to date"))
        return 1 if stale else 0
    if args and (len(args) != 2 or args[0] != '--out'):
        raise SystemExit(__doc__)
    folder = args[1] if args else CPU
    os.makedirs(folder, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(folder, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    print("%d sequences, %d decode rows written to %s" % (len(seqs), len(rows), folder))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
